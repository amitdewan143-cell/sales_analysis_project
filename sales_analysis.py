import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

data = { "Brand": [
        "Samsung", "Apple", "OnePlus",
        "Samsung", "Apple", "OnePlus"
    ],
    "Model": [
        "A55", "iPhone 15", "12R",
        "S24", "iPhone 16", "13"
    ],
    "Price": [
        35000, 70000, 40000,
        80000, 85000, 45000
    ],
    "Units_Sold": [
        20, 15, 25, 10, 18, 22
    ]
}

df = pd.DataFrame(data)

# Revenue
df["Revenue"] = df["Price"] * df["Units_Sold"]

print(df)

# Total revenue
print("\nTotal Revenue:", df["Revenue"].sum())

# Brand-wise sales
brand_sales = df.groupby("Brand")["Units_Sold"].sum()

print("\nBrand-wise Sales:")
print(brand_sales)

# Highest revenue phone
highest_revenue = df.loc[df["Revenue"].idxmax()]

print("\nHighest Revenue Phone:")
print(highest_revenue)

# Chart
plt.bar(
    brand_sales.index,
    brand_sales.values
)

plt.title("Mobile Sales by Brand")
plt.xlabel("Brand")
plt.ylabel("Units Sold")
plt.show()